import { Toaster } from "react-hot-toast";
import { Instrument_Sans } from "next/font/google";
import "@/styles/globals.css";
import { cookies } from "next/headers";

const instrumentSans = Instrument_Sans({
  variable: "--font-instrument-sans",
  subsets: ["latin"],
});

export const metadata = {
  title: "leetpulse - A Spaced Repetition Tracker",
  description: "Generated by create next app",
  icons: {
    icon: "/favicon.ico",
  },
};

export default async function RootLayout({ children }) {
  const cookieStore = await cookies();
  const savedTheme = cookieStore.get("theme")?.value || "dark";

  let themeClass = savedTheme;
  if (savedTheme === "system") {
    const prefersDark = window.matchMedia(
      "(prefers-color-scheme: dark)"
    ).matches;
    themeClass = prefersDark ? "dark" : "light";
  } else {
    themeClass = savedTheme;
  }

  return (
    <html lang="en">
      <body className={`${instrumentSans.variable} antialiased ${themeClass}`}>
        {children}

        <Toaster
          position="top-right"
          reverseOrder={false}
          toastOptions={{
            style: {
              background: "var(--bg-2)",
              color: "var(--text-primary)",
            },
          }}
        />
      </body>
    </html>
  );
}
